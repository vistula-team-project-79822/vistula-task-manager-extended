-- Vistula Task Manager Extended - database structure
-- Run this whole file in the Supabase SQL Editor of the demonstration project.

-- 1) categories (the "one" side of the relationship)
create table public.categories (
  id   bigint generated by default as identity primary key,
  name text not null
);

-- 2) tasks (the "many" side) - category_id is a foreign key to categories.id
create table public.tasks (
  id          bigint generated by default as identity primary key,
  title       text not null,
  description text,
  completed   boolean not null default false,
  category_id bigint references public.categories (id) on delete set null
);

-- Index on the foreign key: speeds up /tasks?category_id=eq.1
create index tasks_category_id_idx on public.tasks (category_id);

-- 3) Row Level Security (demonstration database: the public anon key may read and write)
alter table public.categories enable row level security;
alter table public.tasks      enable row level security;

grant select, insert, update, delete on public.categories to anon;
grant select, insert, update, delete on public.tasks      to anon;

create policy "categories read"   on public.categories for select to anon using (true);
create policy "categories insert" on public.categories for insert to anon with check (true);

create policy "tasks read"   on public.tasks for select to anon using (true);
create policy "tasks insert" on public.tasks for insert to anon with check (true);
create policy "tasks update" on public.tasks for update to anon using (true) with check (true);
create policy "tasks delete" on public.tasks for delete to anon using (true);

-- 4) Example data (ids are generated automatically, so tasks look the category up by name)
insert into public.categories (name) values ('University'), ('Work'), ('Personal');

insert into public.tasks (title, description, completed, category_id) values
  ('Finish Team Project assignment', 'Extended Task Manager with categories', false,
     (select id from public.categories where name = 'University')),
  ('Revise SQL joins', 'Foreign keys and one-to-many', true,
     (select id from public.categories where name = 'University')),
  ('Update CV', 'Add the latest internship', false,
     (select id from public.categories where name = 'Work')),
  ('Buy groceries', null, false,
     (select id from public.categories where name = 'Personal'));
